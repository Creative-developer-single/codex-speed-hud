import { describe, expect, it } from 'vitest'
import { SpeedMetrics } from '../src/metrics.mjs'

function fixture() {
  let now = 0
  const texts = []
  const metrics = new SpeedMetrics({ countTokens: text => { texts.push(text); return text.length }, now: () => now })
  const emit = (method, params = {}, at = now, hostId = 'local') => { now = at; metrics.accept({ method, params: { threadId: 't', turnId: 'u', ...params }, hostId }, at) }
  const snapshot = (at = now, threadId = 't', hostId = 'local') => { now = at; return metrics.snapshot(threadId, hostId) }
  return { metrics, texts, emit, snapshot }
}

describe('TTFT and visible output speed', () => {
  it('restores prior response metadata without replacing a newer completed response', () => {
    const f = fixture()
    const previousResponse = { turnId: 'old', model: 'gpt-6.1-sol', reasoningEffort: 'high', fastMode: null }
    f.metrics.applyNative({ threadId: 't', previousResponse })
    expect(f.snapshot()).toMatchObject({ recordedModel: 'GPT-6.1 Sol', recordedEffort: 'high', recordedFastMode: null })
    f.metrics.accept({ method: 'turn/started', params: { threadId: 't', turn: { id: 'u' } }, settings: { modelLabel: 'GPT-6 Luna', reasoningEffort: 'medium', fastMode: false } }, 0)
    expect(f.snapshot().recordedModel).toBe('GPT-6.1 Sol')
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'abc' }, 100)
    f.emit('item/completed', { item: { id: 'i', type: 'agentMessage', text: 'abc' } }, 200)
    f.metrics.applyNative({ threadId: 't', turnId: 'u', model: 'gpt-6-luna', previousResponse })
    expect(f.snapshot()).toMatchObject({ recordedModel: 'GPT-6 Luna', recordedEffort: 'medium', recordedFastMode: false, recordedTurnId: 'u' })
    expect(f.snapshot(200, 'other').recordedModel).toBeNull()
  })
  it('retains first-stream snapshots until a newer measurement arrives without native recalibration', () => {
    const f = fixture()
    f.emit('turn/started', { turn: { id: 'u' } }, 0)
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'abc' }, 300)
    f.metrics.applyNative({ threadId: 't', turnId: 'u', nativeTTFT: 200 })
    f.emit('turn/completed', { turn: { id: 'u', status: 'completed' } }, 400)
    expect(f.snapshot()).toMatchObject({ firstTokenMs: 300, firstHeld: true })
    f.emit('turn/started', { turnId: 'v', turn: { id: 'v' } }, 1000)
    expect(f.snapshot()).toMatchObject({ firstTokenMs: 300, firstHeld: true, firstTokenTurnId: 'u' })
    f.metrics.applyNative({ threadId: 't', turnId: 'u', nativeTTFT: 150 })
    expect(f.snapshot().firstTokenMs).toBe(300)
    f.emit('item/agentMessage/delta', { turnId: 'v', itemId: 'j', delta: 'new' }, 1200)
    expect(f.snapshot()).toMatchObject({ firstTokenMs: 200, firstHeld: false, firstTokenTurnId: 'v', firstTokenSource: 'stream-event' })
    f.metrics.applyNative({ threadId: 't', turnId: 'u', nativeTTFT: 1 })
    expect(f.snapshot().firstTokenMs).toBe(200)
    f.emit('item/started', { turnId: 'v', item: { id: 'tool', type: 'commandExecution' } }, 1300)
    expect(f.snapshot().firstTokenMs).toBe(200)
    f.metrics.applyNative({ threadId: 't', turnId: 'v', nativeTTFT: 50 })
    expect(f.snapshot()).toMatchObject({ firstTokenMs: 200, firstTokenSource: 'stream-event' })
    expect(f.snapshot(1400, 'other').firstTokenMs).toBeNull()
    expect(f.snapshot(1400, 't', 'remote').firstTokenMs).toBeNull()
  })
  it('does not mix historical effective-content TTFT into the first-flow field', () => {
    const f = fixture()
    const previousFirstToken = { turnId: 'old', ms: 42 }
    f.metrics.applyNative({ threadId: 't', previousFirstToken })
    expect(f.snapshot()).toMatchObject({ firstTokenMs: null, firstTokenSource: null, firstHeld: false })
    f.emit('turn/started', { turn: { id: 'u' } }, 1000)
    expect(f.snapshot().firstTokenMs).toBeNull()
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'abc' }, 1100)
    f.metrics.applyNative({ threadId: 't', turnId: 'u', previousFirstToken })
    expect(f.snapshot()).toMatchObject({ firstTokenMs: 100, firstTokenSource: 'stream-event' })
  })
  it.each(['completed', 'interrupted', 'failed'])('retains the last text sample after %s, across waits and new turns', terminal => {
    const f = fixture()
    f.emit('turn/started', { turn: { id: 'u' } })
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'abc' }, 100)
    f.snapshot()
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'def' }, 600)
    expect(f.snapshot().displayTPS).toBe(12)
    f.snapshot(900) // Idle renders may change the live rate, but not the retained sample.
    f.emit('item/completed', { item: { id: 'i', type: 'agentMessage', text: 'abcdef' } }, 1000)
    expect(f.snapshot()).toMatchObject({ liveTPS: null, displayTPS: 12, speedHeld: true })
    f.emit('item/started', { item: { id: 'tool', type: 'commandExecution' } }, 1100)
    expect(f.snapshot().displayTPS).toBe(12)
    f.emit('turn/completed', { turn: { id: 'u', status: terminal } }, 1200)
    expect(f.snapshot(5000)).toMatchObject({ liveTPS: null, displayTPS: 12, speedHeld: true })
    f.emit('turn/started', { turnId: 'v', turn: { id: 'v' } }, 5100)
    expect(f.snapshot().displayTPS).toBe(12)
    expect(f.snapshot(5100, 'other').displayTPS).toBeNull()
    expect(f.snapshot(5100, 't', 'remote').displayTPS).toBeNull()
    f.emit('item/agentMessage/delta', { turnId: 'v', itemId: 'j', delta: 'ab' }, 5200)
    f.snapshot()
    f.emit('item/agentMessage/delta', { turnId: 'v', itemId: 'j', delta: 'cd' }, 5700)
    expect(f.snapshot()).toMatchObject({ displayTPS: 8, speedHeld: false })
  })
  it('captures a final delta even if completion precedes the next render', () => {
    const f = fixture()
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'abc' }, 100)
    f.snapshot()
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'def' }, 600)
    f.emit('item/completed', { item: { id: 'i', type: 'agentMessage', text: 'abcdef' } }, 600)
    expect(f.snapshot()).toMatchObject({ liveTPS: null, displayTPS: 12, speedHeld: true })
  })
  it('keeps session totals separate and resets average speed per user turn', () => {
    const f = fixture()
    f.emit('turn/started', { turn: { id: 'u' } }, 0)
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'abc' }, 100)
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'def' }, 600)
    expect(f.snapshot()).toMatchObject({ firstTokenMs: 100, firstTokenSource: 'stream-event', averageTPS: 12 })
    f.emit('turn/completed', { turn: { id: 'u', status: 'completed' } }, 800)
    f.metrics.applyNative({ threadId: 't', turnId: 'u', nativeTTFT: 70, sessionUsage: { input_tokens: 1000, cached_input_tokens: 800, output_tokens: 200 } })
    expect(f.snapshot()).toMatchObject({ firstTokenMs: 100, firstTokenSource: 'stream-event', sessionTokens: 1200, averageTPS: 12 })
    f.emit('turn/started', { turnId: 'v', turn: { id: 'v' } }, 2000)
    expect(f.snapshot().averageTPS).toBeNull()
    f.emit('item/agentMessage/delta', { turnId: 'v', itemId: 'j', delta: 'abc' }, 2100)
    f.emit('item/agentMessage/delta', { turnId: 'v', itemId: 'j', delta: 'def' }, 3100)
    // Only this user's turn: 6 tokens / 1 second, excluding the previous 12 tok/s turn.
    expect(f.snapshot().averageTPS).toBe(6)
    expect(f.snapshot(10000).averageTPS).toBe(6)
    expect(f.snapshot(10000, 'other').averageTPS).toBeNull()
    expect(f.snapshot(10000, 't', 'remote').sessionTokens).toBeNull()
  })
  it('weights intermediate messages in one reply and excludes tool waits', () => {
    const f = fixture()
    f.emit('turn/started', { turn: { id: 'u' } })
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'abc' }, 100)
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'def' }, 600)
    f.emit('item/completed', { item: { id: 'i', type: 'agentMessage', text: 'abcdef' } })
    f.emit('item/started', { item: { id: 'tool', type: 'commandExecution' } }, 700)
    f.emit('item/completed', { item: { id: 'tool', type: 'commandExecution' } }, 10000)
    f.emit('item/agentMessage/delta', { itemId: 'j', delta: 'a'.repeat(10) }, 10100)
    f.emit('item/agentMessage/delta', { itemId: 'j', delta: 'b'.repeat(10) }, 11100)
    f.emit('turn/completed', { turn: { id: 'u', status: 'completed' } }, 12000)
    expect(f.snapshot().averageTPS).toBeCloseTo(26 / 1.5)
    expect(f.snapshot(20000).averageTPS).toBeCloseTo(26 / 1.5)
  })
  it('times the first model event including empty reasoning headers, excluding user and tool events', () => {
    const f = fixture()
    f.emit('turn/started', { turn: { id: 'u' } })
    f.emit('item/started', { item: { id: 'user', type: 'userMessage' } }, 10)
    f.emit('item/started', { item: { id: 'tool', type: 'commandExecution' } }, 20)
    expect(f.snapshot().firstTokenMs).toBeNull()
    f.emit('item/reasoning/summaryPartAdded', { itemId: 'r', summaryIndex: 0 }, 50)
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'body' }, 300)
    expect(f.snapshot()).toMatchObject({ firstStreamMs: 50, firstVisibleMs: 300, firstTokenMs: 50 })
  })
  it('does not invent a first-event start when joining before a reasoning delta', () => {
    const f = fixture()
    f.emit('item/reasoning/textDelta', { itemId: 'r', delta: 'thinking' }, 1000)
    f.emit('turn/started', { turn: { id: 'u' } }, 1100)
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'body' }, 1200)
    expect(f.snapshot()).toMatchObject({ firstStreamMs: null, firstVisibleMs: null, firstTokenMs: null })
  })
  it('excludes long pauses and unobserved hydrated text from the session average', () => {
    const f = fixture()
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'abc' }, 100)
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'def' }, 600)
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'ghi' }, 10000)
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'jkl' }, 10500)
    f.emit('item/completed', { item: { type: 'agentMessage', id: 'i', text: 'unobserved prefix abcdefghijkl' } })
    expect(f.snapshot().averageTPS).toBe(12)
    f.emit('thread/tokenUsage/updated', { tokenUsage: { total: { inputTokens: 100, cachedInputTokens: 80, outputTokens: 20 } } })
    expect(f.snapshot().sessionTokens).toBe(120)
  })
  it('times first visible text, counts accumulated text, keeps native TTFT distinct', () => {
    const f = fixture()
    f.emit('turn/started', { turn: { id: 'u' } }, 0)
    f.emit('item/reasoning/summaryTextDelta', { itemId: 'r', delta: 'not visible output' }, 100)
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'hello' }, 300)
    expect(f.snapshot(300).firstVisibleMs).toBe(300)
    expect(f.snapshot(300).firstStreamMs).toBe(100)
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: ' world' }, 800)
    expect(f.snapshot(800).visibleTokens).toBe(11)
    expect(f.texts.at(-1)).toBe('hello world')
    expect(f.snapshot(800).liveTPS).toBeGreaterThan(0)
    f.metrics.applyNative({ threadId: 't', turnId: 'u', nativeTTFT: 100, model: 'gpt-test' })
    expect(f.snapshot().nativeTTFT).toBe(100)
    expect(f.snapshot().firstVisibleMs).toBe(300)
  })
  it('does not manufacture TTFT when attaching in the middle of a turn', () => {
    const f = fixture()
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'hello' }, 5000)
    expect(f.snapshot().firstVisibleMs).toBeNull()
    f.emit('turn/started', { turn: { id: 'u' } }, 5100)
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: ' world' }, 5200)
    expect(f.snapshot().firstVisibleMs).toBeNull()
  })
  it('resets rate timing across tools and hides rates during tools or stalls', () => {
    const f = fixture()
    f.emit('turn/started', { turn: { id: 'u' } })
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'abc' }, 100)
    f.snapshot(100)
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'def' }, 600)
    expect(f.snapshot().liveTPS).not.toBeNull()
    f.emit('item/completed', { item: { id: 'i', type: 'agentMessage', text: 'abcdef' } })
    f.emit('item/started', { item: { id: 'tool', type: 'commandExecution' } }, 700)
    expect(f.snapshot().status).toBe('tool')
    expect(f.snapshot().liveTPS).toBeNull()
    f.emit('item/completed', { item: { id: 'tool', type: 'commandExecution' } }, 10000)
    f.emit('item/agentMessage/delta', { itemId: 'next', delta: 'abc' }, 10100)
    expect(f.snapshot().liveTPS).toBeNull()
    f.emit('item/agentMessage/delta', { itemId: 'next', delta: 'def' }, 10600)
    expect(f.snapshot().liveTPS).toBeCloseTo(12)
    expect(f.snapshot(12500).liveTPS).toBeNull()
  })
  it('separates turns and hosts, ignores duplicate starts and terminal deltas', () => {
    const f = fixture()
    f.emit('turn/started', { turn: { id: 'u' } }, 0)
    f.emit('turn/started', { turn: { id: 'u' } }, 200)
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'a' }, 300)
    expect(f.snapshot().firstVisibleMs).toBe(300)
    f.emit('turn/started', { turn: { id: 'u' } }, 400, 'remote:x')
    f.metrics.applyNative({ threadId: 't', turnId: 'old', nativeTTFT: 1 })
    expect(f.snapshot().nativeTTFT).toBeNull()
    expect(f.snapshot(400, 't', 'remote:x').firstVisibleMs).toBeNull()
    f.emit('turn/completed', { turn: { id: 'u', status: 'interrupted' } }, 500)
    f.emit('item/agentMessage/delta', { itemId: 'i', delta: 'ignored' }, 600)
    f.emit('item/started', { item: { id: 'late-tool', type: 'commandExecution' } }, 700)
    expect(f.snapshot().visibleTokens).toBe(1)
    expect(f.snapshot().status).toBe('interrupted')
    expect([...f.metrics.turns.values()][0].items.get('i').text).toBe('')
  })
  it('does not count reasoning twice or replace native values on temporary log failure', () => {
    const f = fixture()
    f.emit('turn/started', { turn: { id: 'u' } })
    f.emit('thread/tokenUsage/updated', { tokenUsage: { last: { outputTokens: 100, reasoningOutputTokens: 80 } } })
    f.metrics.applyNative({ threadId: 't', turnId: 'u', nativeTTFT: 0 })
    f.metrics.applyNative({ threadId: 't', turnId: 'u', source: 'missing' })
    expect(f.snapshot().outputTokens).toBe(100)
    expect(f.snapshot().reasoningTokens).toBe(80)
    expect(f.snapshot().nativeTTFT).toBe(0)
  })
  it('does not switch back to an older turn on a delayed completion', () => {
    const f = fixture()
    f.emit('turn/started', { turn: { id: 'u' } }, 0)
    f.emit('turn/started', { turnId: 'new', turn: { id: 'new' } }, 100)
    f.emit('turn/completed', { turn: { id: 'u', status: 'completed' } }, 200)
    expect(f.snapshot().turnId).toBe('new')
  })
})
