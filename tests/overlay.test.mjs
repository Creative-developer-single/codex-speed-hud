import { describe, expect, it } from 'vitest'
import { JSDOM } from 'jsdom'
import { installHUD } from '../src/overlay.mjs'

describe('overlay lifecycle and chat switching', () => {
  it('retains native snapshots between calls and uses a per-turn native average without new rows', () => {
    const dom = new JSDOM('<body><div data-app-action-sidebar-thread-active="true" data-app-action-sidebar-thread-id="t"></div></body>', { url: 'http://127.0.0.1/' })
    const w = dom.window, hud = installHUD(w, s => s.length)
    w.dispatchEvent(new w.MessageEvent('message', { data: { type: 'mcp-notification', method: 'turn/started', params: { threadId: 't', turn: { id: 'u' } } } }))
    const epoch = Date.now() + 1000
    const stream = { source: 'native-observer', id: 'a', threadId: 't', turnId: 'u', kind: 'response', status: 'completed', startedAt: epoch, completedAt: epoch + 1000, durationMs: 1000, toolTPS: 20, toolLastAt: epoch + 900, firstStreamMs: 400, turnAverageTPS: 80 }
    hud.applyNative({ threadId: 't', turnId: 'u', nativeStream: stream })
    const shadow = w.document.getElementById('codex-speed-hud').shadowRoot
    expect(shadow.querySelector('[data-speed]').textContent).toBe('20.0')
    expect(shadow.querySelector('[data-average]').textContent).toBe('80.0 tok/s')
    hud.applyNative({ threadId: 't', turnId: 'u', nativeStream: { ...stream, id: 'b', status: 'waiting', completedAt: null, startedAt: epoch + 1200, durationMs: 0, firstStreamMs: null, toolTPS: null } })
    expect(shadow.querySelector('[data-first]').textContent).toBe('0.40 s')
    expect(shadow.querySelector('[data-speed]').textContent).toBe('20.0')
    expect(shadow.querySelectorAll('dt')).toHaveLength(3)
    hud.destroy(); w.close()
  })
  it('merges compression and tool measurements into the existing gauge and first-flow fields', () => {
    const dom = new JSDOM('<body><div data-app-action-sidebar-thread-active="true" data-app-action-sidebar-thread-id="t"></div></body>', { url: 'http://127.0.0.1/' })
    const hud = installHUD(dom.window, s => s.length)
    const shadow = dom.window.document.getElementById('codex-speed-hud').shadowRoot
    const epoch = Date.now() + 1000
    hud.applyNative({ threadId: 't', nativeStream: { kind: 'compaction', startedAt: epoch, completedAt: epoch + 10000, totalAverageTPS: 100, firstStreamMs: 700 } })
    expect(shadow.querySelector('[data-speed]').textContent).toBe('100.0')
    expect(shadow.querySelector('[data-first]').textContent).toBe('0.70 s')
    expect(shadow.querySelector('[data-speed]').title).toContain('压缩总耗时')
    expect(shadow.querySelector('[data-activity]')).toBeNull()
    expect(shadow.querySelectorAll('dt')).toHaveLength(3)
    expect(hud.snapshot().measurementKind).toBe('compaction-average')
    hud.applyNative({ threadId: 't', nativeStream: { kind: 'response', toolTPS: 20, toolLastAt: epoch + 12000, toolTokens: 10, toolHeld: true, firstStreamMs: 400 } })
    expect(shadow.querySelector('[data-speed]').textContent).toBe('20.0')
    expect(shadow.querySelector('[data-first]').textContent).toBe('0.40 s')
    expect(shadow.querySelector('[data-speed]').title).toContain('工具参数')
    hud.destroy(); dom.window.close()
  })
  it.each(['local', 'remote-ssh:developer'])('matches host-qualified sidebar IDs for %s', hostId => {
    const dom = new JSDOM('<body><div data-app-action-sidebar-thread-active="true"></div></body>', { url: 'http://127.0.0.1/' })
    const w = dom.window
    const selected = w.document.querySelector('div')
    selected.setAttribute('data-app-action-sidebar-thread-id', `${hostId}:t`)
    selected.setAttribute('data-app-action-sidebar-thread-host-id', hostId)
    const hud = installHUD(w, text => text.length)
    w.dispatchEvent(new w.MessageEvent('message', { data: {
      type: 'mcp-notification', hostId, method: 'turn/started', params: { threadId: 't', turn: { id: 'u' } },
    } }))
    expect(hud.snapshot()).toMatchObject({ hostId, threadId: 't', turnId: 'u', status: 'waiting' })
    hud.destroy(); w.close()
  })
  it('observes notifications without affecting the original listener and cleans up', () => {
    const dom = new JSDOM('<body><div data-app-action-sidebar-thread-active="true" data-app-action-sidebar-thread-id="t"></div></body>', { url: 'http://127.0.0.1/' })
    const w = dom.window
    w.document.body.insertAdjacentHTML('afterbegin', '<div data-app-shell-header-slot-content><div data-toolbar><div aria-hidden="true"></div><span><button data-app-shell-workspace-layout-toggle="main" class="button-toolbar">+</button></span></div></div>')
    let clock = 0
    w.performance.now = () => clock
    let originalCalls = 0
    w.addEventListener('message', () => originalCalls++)
    const hud = installHUD(w, text => text.length)
    expect(installHUD(w, text => text.length)).toBe(hud)
    const emit = (method, params) => w.dispatchEvent(new w.MessageEvent('message', { data: { type: 'mcp-notification', method, params: { threadId: 't', turnId: 'u', ...params } } }))
    emit('turn/started', { turn: { id: 'u' } })
    clock = 100; emit('item/agentMessage/delta', { itemId: 'i', delta: 'a' })
    clock = 600; emit('item/agentMessage/delta', { itemId: 'i', delta: 'bc' })
    expect(hud.snapshot().firstVisibleMs).toBe(100)
    expect(hud.snapshot().averageTPS).toBe(6)
    expect(originalCalls).toBe(3)
    const root = w.document.getElementById('codex-speed-hud')
    expect(root.shadowRoot.querySelector('[data-native]')).toBeNull()
    expect(root.shadowRoot.querySelector('[data-first]').textContent).toBe('0.10 s')
    hud.applyNative({ threadId: 't', turnId: 'u', nativeTTFT: 50, sessionUsage: { input_tokens: 1_000_000, cached_input_tokens: 800_000, output_tokens: 200_000 } })
    expect(root.shadowRoot.querySelector('[data-first]').textContent).toBe('0.10 s')
    expect(root.shadowRoot.querySelector('[data-tokens]').textContent).toBe('1.2M/—$')
    hud.applyNative({ threadId: 't', sessionCost: { usd: 1.23, requests: 2, assumedTier: 1, unpriced: 0, priceDate: '2026-10-12', solThreshold: 500_000 } })
    expect(root.shadowRoot.querySelector('[data-tokens]').textContent).toBe('1.2M/1.23$')
    expect(root.shadowRoot.querySelector('[data-tokens]').title).toContain('按标准价格估算')
    expect(root.shadowRoot.querySelector('.meter').getAttribute('aria-label')).toContain('tok/s')
    expect(root.shadowRoot.querySelector('[data-speed]').textContent).not.toContain('≈')
    expect(root.shadowRoot.querySelector('[data-average]').textContent).not.toContain('≈')
    expect(root.shadowRoot.querySelector('.note')).toBeNull()
    expect(root.shadowRoot.querySelectorAll('dt svg')).toHaveLength(3)
    expect([...root.shadowRoot.querySelectorAll('dt')].map(n => n.textContent)).toEqual(['首流', '本次平均', '累计'])
    expect(root.shadowRoot.querySelector('.dial')).not.toBeNull()
    const frozen = root.shadowRoot.querySelector('[data-speed]').textContent
    emit('item/completed', { item: { id: 'i', type: 'agentMessage', text: 'abc' } })
    clock = 5000; hud.snapshot()
    expect(root.shadowRoot.querySelector('[data-speed]').textContent).toBe(frozen)
    expect(root.shadowRoot.querySelector('[data-speed]').title).toContain('上一次')
    emit('turn/completed', { turn: { id: 'u', status: 'completed' } })
    emit('turn/started', { turnId: 'v', turn: { id: 'v' } })
    hud.snapshot()
    expect(root.shadowRoot.querySelector('[data-first]').textContent).toBe('0.10 s')
    expect(root.shadowRoot.querySelector('[data-first]').title).toContain('上一次')
    root.shadowRoot.querySelector('[data-collapse]').click()
    expect(root.shadowRoot.querySelector('main').hidden).toBe(true)
    w.document.querySelector('[data-app-action-sidebar-thread-id]').setAttribute('data-app-action-sidebar-thread-id', 'other')
    expect(hud.snapshot().status).toBe('no-turn')
    expect(root.shadowRoot.querySelector('[data-tokens]').textContent).toBe('—/—$')
    expect(root.shadowRoot.querySelector('[data-speed]').textContent).toBe('—')
    root.shadowRoot.querySelector('[data-close]').click()
    hud.snapshot(); expect(root.isConnected).toBe(true)
    const launcher = w.document.querySelector('[data-codex-speed-hud-toggle]')
    expect(root.shadowRoot.querySelector('section').hidden).toBe(true)
    expect(root.hidden).toBe(true)
    expect(launcher.hidden).toBe(false)
    expect(launcher.parentElement).toBe(w.document.querySelector('[data-toolbar]'))
    expect(launcher.className).toBe('button-toolbar')
    expect(w.document.activeElement).toBe(launcher)
    expect(launcher.getAttribute('aria-expanded')).toBe('false')
    expect(hud.snapshot().visible).toBe(false)
    launcher.click()
    expect(root.shadowRoot.querySelector('section').hidden).toBe(false)
    expect(root.shadowRoot.querySelector('main').hidden).toBe(false)
    expect(root.hidden).toBe(false)
    expect(launcher.getAttribute('aria-expanded')).toBe('true')
    expect(hud.snapshot().visible).toBe(true)
    // The host can replace its toolbar while changing chats or window layout.
    w.document.querySelector('[data-toolbar]').replaceWith(w.document.querySelector('[data-toolbar]').cloneNode(true))
    w.document.querySelector('[data-codex-speed-hud-toggle]').remove()
    hud.snapshot()
    expect(w.document.querySelectorAll('[data-codex-speed-hud-toggle]')).toHaveLength(1)
    expect(w.document.querySelector('[data-codex-speed-hud-toggle]')).toBe(launcher)
    launcher.click()
    expect(hud.snapshot().visible).toBe(false)
    root.shadowRoot.querySelector('[data-close]').click()
    hud.show(); expect(root.isConnected).toBe(true)
    expect(root.shadowRoot.querySelector('section').hidden).toBe(false)
    hud.destroy(); expect(w.__codexSpeedHUD).toBeUndefined()
    expect(root.isConnected).toBe(false)
    expect(w.document.querySelector('[data-codex-speed-hud-toggle]')).toBeNull()
    dom.window.close()
  })
  it('shows a read-only completed-output record, ignoring subsequent composer edits', () => {
    const dom = new JSDOM('<body><div data-app-action-sidebar-thread-active="true" data-app-action-sidebar-thread-id="t"></div><button data-codex-intelligence-trigger="true" data-selected-reasoning-effort="high" data-fast-mode-enabled="true"><span class="_ModelPickerTriggerModelText_test">GPT-6.1 Sol</span></button></body>', { url: 'http://127.0.0.1/' })
    const w = dom.window
    const trigger = w.document.querySelector('button')
    trigger.getBoundingClientRect = () => ({ width: 100 })
    let clicks = 0
    trigger.addEventListener('click', () => clicks++)
    const hud = installHUD(w, text => text.length)
    const shadow = w.document.getElementById('codex-speed-hud').shadowRoot
    const emit = (method, turnId, extra = {}) => w.dispatchEvent(new w.MessageEvent('message', { data: { type: 'mcp-notification', hostId: 'local', method, params: { threadId: 't', turnId, ...extra } } }))
    expect(hud.snapshot().recordedModel).toBeNull()
    emit('turn/started', 'u', { turn: { id: 'u' } })
    // Changing the next-request selector during a reply must not relabel that reply.
    trigger.setAttribute('data-fast-mode-enabled', 'false')
    trigger.setAttribute('data-selected-reasoning-effort', 'medium')
    trigger.querySelector('span').textContent = 'GPT-6 Luna'
    emit('item/agentMessage/delta', 'u', { itemId: 'i', delta: 'abc' })
    expect(hud.snapshot().recordedModel).toBeNull()
    emit('item/completed', 'u', { item: { id: 'i', type: 'agentMessage', text: 'abc' } })
    expect(hud.snapshot()).toMatchObject({ recordedModel: 'GPT-6.1 Sol', recordedEffort: 'high', recordedFastMode: true })
    expect(shadow.querySelector('[data-model]').textContent).toBe('GPT-6.1 Sol')
    expect(shadow.querySelector('[data-effort]').textContent).toBe('High')
    expect(shadow.querySelector('[data-fast]').textContent).toBe('FAST')
    expect(clicks).toBe(0)
    hud.snapshot()
    expect(shadow.querySelector('[data-model]').textContent).toBe('GPT-6.1 Sol')
    expect(shadow.querySelector('[data-selection]').tagName).toBe('DIV')
    expect(shadow.querySelector('[data-selection] svg')).toBeNull()
    shadow.querySelector('[data-selection]').click()
    expect(clicks).toBe(0)
    emit('turn/started', 'v', { turn: { id: 'v' } })
    expect(hud.snapshot().recordedModel).toBe('GPT-6.1 Sol')
    emit('item/agentMessage/delta', 'v', { itemId: 'j', delta: 'next' })
    emit('item/completed', 'v', { item: { id: 'j', type: 'agentMessage', text: 'next' } })
    hud.snapshot()
    expect(shadow.querySelector('[data-model]').textContent).toBe('GPT-6 Luna')
    expect(shadow.querySelector('[data-effort]').textContent).toBe('Medium')
    expect(shadow.querySelector('[data-fast]').textContent).toBe('标准')
    expect(clicks).toBe(0)
    hud.destroy(); w.close()
  })
})
